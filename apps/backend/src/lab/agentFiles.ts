import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { buildCinematographerReshootSystemPrompt, buildCinematographerSystemPrompt } from "../agents/cinematographer/prompt-v1.js";
import { CINEMATOGRAPHER_PROMPTS_V2 } from "../agents/cinematographer/prompt-v2.js";
import { buildDirectorPatchSystemPromptV2, buildDirectorSystemPromptV2 } from "../agents/director/prompt-v2.js";
import { buildInterrogatorAskSystemPrompt, buildInterrogatorFillSystemPrompt } from "../agents/interrogator/prompt-v2.js";
import { LAB_SPECIALIST_MODEL } from "./sequential.js";

/**
 * The coordinator's subagents and the swarm's teammates are Claude Code agent files,
 * `.claude/agents/lab-*.md`. They are generated from the same versioned prompt files the
 * recipe sends, never written by hand, so all three architectures give each agent the
 * same instructions; a drift test fails if a committed file differs from this output.
 * Regenerate with `npm run -s lab -- export-agents`.
 */
export type LabAgentName = "lab-interrogator" | "lab-director" | "lab-cinematographer";

const LAB = "npm run -s lab --";

function frontmatter(name: LabAgentName, description: string): string {
  return [
    "---",
    `name: ${name}`,
    `description: ${JSON.stringify(description)}`,
    "tools: Bash, Read, SendMessage",
    `model: ${LAB_SPECIALIST_MODEL}`,
    "effort: high",
    "---",
    "<!-- generated by npm run -s lab -- export-agents from the v2 prompt files; do not edit -->",
    "",
  ].join("\n");
}

function sharedRules(name: string, steps: string): string {
  return [
    "## How you work: the lab's rules, enforced in code",
    "",
    "You work on one run. Its folder is `data/lab-runs/<runId>/`; whoever starts you gives you the run id.",
    "",
    `- Read the run with \`${LAB} show <runId>\` (one file: \`${LAB} show <runId> brief.json\`).`,
    `- Save your output (${steps}) only with the save command: one JSON value on stdin, no code fence and no text around it.`,
    "",
    "  ```bash",
    `  ${LAB} save <runId> <step> --by ${name} <<'JSON'`,
    "  { ... }",
    "  JSON",
    "  ```",
    "",
    "- If it prints `\"ok\": false`, its `error` says why: fix exactly that and save again. Three refusals in a row fail the run.",
    "- Never write or edit files in the run folder by hand. Never call any other API. Never generate, render or request an image or a video.",
    "- You cannot talk to the owner.",
  ].join("\n");
}

const COORDINATOR = [
  "## If you were called as a subagent (the coordinator)",
  "",
  "Do what the lead asked: save once, run the check once, and return two lines: what you saved and what the check printed. Do not fix it on your own when the check says `redo`: the lead decides whether you try again, and what to change. Do not call any other agent.",
].join("\n");

function swarm(lines: string[]): string {
  return [
    "## If you are a teammate in a swarm",
    "",
    "Your teammates are `interrogator`, `director` and `cinematographer`; the `lead` only passes messages between the team and the owner and never gives orders. Hand work on yourself with SendMessage. Log every message you send as well:",
    "",
    "```bash",
    `${LAB} log <runId> --from <you> --to <them> "<what you said>"`,
    "```",
    "",
    ...lines,
    "- If a command prints a `stop` route or the run is no longer running, tell the `lead` \"stopped: <reason>\" and stop.",
  ].join("\n");
}

function checkRules(step: "plan" | "shots", who: string, redo: string): string {
  return [
    `2. After each save, run \`${LAB} check <runId> ${step} --by ${who}\`. It prints the outcomes and a route:`,
    "   - `pass`: your part is done.",
    `   - \`redo\`: in a swarm, ${redo} As a subagent, return the outcome instead (see below).`,
    "   - `stop`: your retries are used up; stop and report why.",
  ].join("\n");
}

/** The v1 add-on (patch or reshoot rules) that follows the base prompt. */
function tail(full: string, base: string): string {
  if (!full.startsWith(base)) throw new Error("agent files: a follow-up prompt no longer starts with its base prompt");
  return full.slice(base.length).trim();
}

function interrogator(): string {
  return [
    frontmatter("lab-interrogator", "Lab specialist: asks the owner what the brief leaves open, then fills the brief. Used by /direct; never invoke it on its own."),
    "# The Interrogator (architecture lab)",
    "",
    sharedRules("interrogator", "steps `questions`, then `brief`"),
    "",
    "## Your steps",
    "",
    `1. Read the brief and the website text with \`${LAB} show <runId>\`, and the saved people with \`${LAB} avatars\`.`,
    '2. Save your questions as step `questions`: `{ "questions": [ { "id", "topic", "question", "ifYouDecide" } ] }`.',
    "3. Once the owner's answers are saved (`answers.json`), save the filled brief as step `brief`: `{ productKind, product, audience, tone, setting, character, seconds, mustNotAppear, avatarId }`.",
    `   If the owner gave a website as an answer, read it first with \`${LAB} scrape <runId> <url>\`. If the owner answered "you decide" to the website question, read the URL you suggested in its \`ifYouDecide\` the same way.`,
    "   With no questions at all, save the brief straight away.",
    "",
    COORDINATOR,
    "",
    swarm([
      "- After saving your questions, send them to the `lead` (it asks the owner, saves the answers and messages you back).",
      "- After saving the brief, tell `director` \"brief saved for <runId>\". Answer the Director if it asks about the brief.",
    ]),
    "",
    "## Your instructions",
    "",
    "### When asked for questions",
    "",
    buildInterrogatorAskSystemPrompt(),
    "",
    "### When asked to fill the brief",
    "",
    buildInterrogatorFillSystemPrompt(),
    "",
  ].join("\n");
}

function director(): string {
  const base = buildDirectorSystemPromptV2();
  return [
    frontmatter("lab-director", "Lab specialist: writes the ad's plan (style, scene, assets, shots) and fixes what the plan checks send back. Used by /direct; never invoke it on its own."),
    "# The Director (architecture lab)",
    "",
    sharedRules("director", "step `plan`"),
    "",
    "## Your steps",
    "",
    "1. Read `brief.json`. Save the plan as step `plan`: `{ styleLine, scene, assets, shots }`.",
    checkRules(
      "plan",
      "director",
      "fix exactly the failing checks listed in the outcomes and save a new plan with the same assets (same handles, kinds and order; descriptions may change). Every new plan uses one of your 2 retries.",
    ),
    "",
    COORDINATOR,
    "",
    swarm([
      "- When the plan checks pass, tell `cinematographer` \"plan <n> passed for <runId>\".",
      "- You may ask `interrogator` about the brief. If the Cinematographer asks about a shot, answer it; if you save a new plan because of it, tell the Cinematographer its cameras are now stale.",
    ]),
    "",
    "## Your instructions",
    "",
    base,
    "",
    "### When the checks send a plan back",
    "",
    tail(buildDirectorPatchSystemPromptV2(), base),
    "",
  ].join("\n");
}

function cinematographer(): string {
  const v2 = CINEMATOGRAPHER_PROMPTS_V2;
  return [
    frontmatter("lab-cinematographer", "Lab specialist: writes one camera per shot (framing, lens, move, light) and reshoots what the shot checks send back. Used by /direct; never invoke it on its own."),
    "# The Cinematographer (architecture lab)",
    "",
    sharedRules("cinematographer", "step `cameras`"),
    "",
    "## Your steps",
    "",
    '1. Read the latest plan and its number (`run.attempts.plan` in `lab show`). Save the cameras as step `cameras`: `{ "forPlan": <that number>, "cameras": [ { shot, framing, lensMm, move, light } ] }`, shots numbered from 1. If the plan changed meanwhile, the save is refused: read the new plan and shoot again.',
    checkRules(
      "shots",
      "cinematographer",
      "rewrite only the shots listed in the route and keep every other camera exactly as it was. Every new camera set uses one of your 2 retries.",
    ),
    "",
    COORDINATOR,
    "",
    swarm([
      `- When the shot checks pass, run \`${LAB} assemble <runId> --by cinematographer\` and tell the \`lead\` "done: <runId>".`,
      "- You may ask `director` about a shot before you shoot it.",
    ]),
    "",
    "## Your instructions",
    "",
    v2.system,
    "",
    "### When the checks send shots back",
    "",
    tail(buildCinematographerReshootSystemPrompt(), buildCinematographerSystemPrompt()),
    "",
  ].join("\n");
}

export function renderAgentFiles(): Record<LabAgentName, string> {
  return {
    "lab-interrogator": interrogator(),
    "lab-director": director(),
    "lab-cinematographer": cinematographer(),
  };
}

export async function writeAgentFiles(dir: string = path.join(".claude", "agents")): Promise<{ files: string[] }> {
  await mkdir(dir, { recursive: true });
  const files: string[] = [];
  for (const [name, text] of Object.entries(renderAgentFiles())) {
    const file = path.join(dir, `${name}.md`);
    await writeFile(file, text, "utf8");
    files.push(file);
  }
  return { files };
}
